const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('xh', {
    getState: () => ipcRenderer.invoke('get-state'),
    update: (partial) => ipcRenderer.invoke('update-settings', partial),
    setConfig: (partial) => ipcRenderer.invoke('set-config', partial),
    profile: (args) => ipcRenderer.invoke('profile', args),
    setVisible: (v) => ipcRenderer.invoke('set-visible', v),
    checkUpdate: () => ipcRenderer.invoke('update-check'),
    installUpdate: () => ipcRenderer.invoke('update-install'),
    openUrl: (u) => ipcRenderer.invoke('open-url', u),
    onState: (cb) => ipcRenderer.on('state', (e, s) => cb(s)),
    onSettings: (cb) => ipcRenderer.on('settings', (e, s) => cb(s)),
    setExtras: (p) => ipcRenderer.invoke('set-extras', p),
    checklistPreset: (k) => ipcRenderer.invoke('checklist-preset', k),
    wlCapture: (delay) => ipcRenderer.invoke('wl-capture', delay),
    backupExport: (o) => ipcRenderer.invoke('backup-export', o),
    backupSave: (o) => ipcRenderer.invoke('backup-save', o),
    backupOpen: () => ipcRenderer.invoke('backup-open'),
    backupInspect: (t) => ipcRenderer.invoke('backup-inspect', t),
    backupImport: (o) => ipcRenderer.invoke('backup-import', o),
    onChecklist: (cb) => ipcRenderer.on('checklist', (e, c) => cb(c)),
    onSamplerConfig: (cb) => ipcRenderer.on('sampler-config', (e, c) => cb(c)),
    onSamplerGeom: (cb) => ipcRenderer.on('sampler-geom', (e, g) => cb(g)),
    samplerSample: (a) => ipcRenderer.send('sampler-sample', a),
    samplerError: (m) => ipcRenderer.send('sampler-error', m),
    timerStart: (w) => ipcRenderer.invoke('timer-start', w),
    timerStop: (id) => ipcRenderer.invoke('timer-stop', id),
    timerAdd: (o) => ipcRenderer.invoke('timer-add', o),
    onTimer: (cb) => ipcRenderer.on('timer', (e, t) => cb(t)),
    onTimerAlarm: (cb) => ipcRenderer.on('timer-alarm', (e, a) => cb(a)),
    timerBeeped: () => ipcRenderer.send('timer-beeped'),
    aimOpen: () => ipcRenderer.invoke('aim-open'),
    wikiOpen: (tab) => ipcRenderer.invoke('wiki-open', tab),
    // HUD v1.5 : wiki instantané, télémètre, boussole, thèmes
    hudGet: () => ipcRenderer.invoke('hud-get'),
    hudAct: (act, data) => ipcRenderer.invoke('hud-act', { act, data }),
    hudExtras: (p) => ipcRenderer.invoke('hud-extras', p),
    getTheme: () => ipcRenderer.invoke('hud-theme-get'),
    setTheme: (id) => ipcRenderer.invoke('hud-theme-set', id),
    onTheme: (cb) => ipcRenderer.on('hud-theme', (e, id) => cb(id)),
    onIndex: (cb) => ipcRenderer.on('hud-index', (e, ix) => cb(ix)),
    onSpotShow: (cb) => ipcRenderer.on('hud-spot-show', (e, o) => cb(o)),
    onRange: (cb) => ipcRenderer.on('hud-range', (e, d) => cb(d)),
    onCompass: (cb) => ipcRenderer.on('hud-compass', (e, d) => cb(d))
});
